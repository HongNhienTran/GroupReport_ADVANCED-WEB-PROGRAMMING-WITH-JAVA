public enum ActivityLevel {
    SEDENTARY,       // Ít vận động, làm việc văn phòng
    LIGHT,           // Vận động nhẹ (tập luyện 1-3 ngày/tuần)
    MODERATE,        // Vận động vừa phải (tập luyện 3-5 ngày/tuần)
    VERY_ACTIVE,     // Vận động nhiều (tập luyện 6-7 ngày/tuần)
    EXTRA_ACTIVE     // Vận động cường độ rất cao / lao động nặng
}
